# 12. Demonstrate AND, OR and NOT logical operators.
first = bool(int(input("Enter 1 for True or 0 for False (first value): ")))
second = bool(int(input("Enter 1 for True or 0 for False (second value): ")))

print("first and second =", first and second)
print("first or second =", first or second)
print("not first =", not first)
